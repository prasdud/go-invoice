// Sustained load: 500 invoices/minute for 10 minutes (the capacity target).
//
// Run:
//   k6 run -e API_KEY=... scripts/loadtest/sustained.js
//   ENGINE=html k6 run -e API_KEY=... -e ENGINE=html scripts/loadtest/sustained.js
//
// Pass criteria (also enforced as thresholds):
//   - zero failures for valid payloads
//   - p99 POST latency < 1s (basic) / < 3s (html)

import http from 'k6/http';
import { check } from 'k6';

const BASE_URL = __ENV.BASE_URL || 'http://localhost:8080';
const API_KEY = __ENV.API_KEY || 'changeme';
const ENGINE = __ENV.ENGINE || 'basic';

export const options = {
  scenarios: {
    sustained: {
      executor: 'constant-arrival-rate',
      rate: 500,
      timeUnit: '1m',
      duration: '10m',
      preAllocatedVUs: 20,
      maxVUs: 100,
    },
  },
  thresholds: {
    http_req_failed: ['rate==0'],
    checks: ['rate==1'],
    http_req_duration: [ENGINE === 'html' ? 'p(99)<3000' : 'p(99)<1000'],
  },
};

const body = JSON.stringify({
  engine: ENGINE,
  payload: {
    invoice_number: 'INV-LOAD',
    date: '2026-11-07',
    bill_to: 'Load Test Co',
    bill_to_address: '1 Load Street\nBenchmark City, CA 94000',
    items: [
      { description: 'Widget A', quantity: 3, rate: 19.99 },
      { description: 'Widget B', quantity: 1, rate: 149.0 },
    ],
    tax_rate: 8.5,
    notes: 'Generated by scripts/loadtest/sustained.js',
  },
});

export default function () {
  const res = http.post(`${BASE_URL}/invoices`, body, {
    headers: { 'Content-Type': 'application/json', 'X-API-Key': API_KEY },
  });
  check(res, { 'created (200)': (r) => r.status === 200 });
}
